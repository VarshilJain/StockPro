end_date = datetime.datetime.now()
start_date = end_date - datetime.timedelta(days=365 * 20)

all_data = []

for sym in SYMBOLS:
    try:
        print(f"Fetching EOD for {sym}")
        df = yf.download(
            sym,
            start=start_date,
            end=end_date,
            interval="1d",
            progress=False,
            auto_adjust=True,
        )
        if df.empty:
            continue

        # Flatten MultiIndex columns if present (yfinance sometimes returns them)
        if isinstance(df.columns, pd.MultiIndex):
            df.columns = df.columns.get_level_values(0)

        # Keep OHLCV + Symbol so downstream scanners can use Volume-based signals.
        df = df[["Open", "High", "Low", "Close", "Volume"]].copy()
        df.index.name = "Date"
        df["Symbol"] = sym
        df.reset_index(inplace=True)                        # Date becomes a column
        df = df[["Symbol", "Date", "Open", "High", "Low", "Close", "Volume"]]  # clean column order

        all_data.append(df)

    except Exception as e:
        print(f"Error fetching {sym}: {e}")

if all_data:
    df_all = pd.concat(all_data, ignore_index=True)
    df_all.to_csv(r"D:\HistoricData\practice.csv", index=False)
    print(f"Saved to practice.csv — {len(df_all)} rows, {df_all['Symbol'].nunique()} symbols")
else:
    print("No data downloaded.")